const genericApiErrorMessage = "انجام این درخواست ممکن نشد. دوباره تلاش کنید.";

function getApiErrorMessageByCode(code: string, requestId?: string) {
  const message = apiErrorMessages[code] ?? genericApiErrorMessage;
  return withRequestId(message, requestId);
}

function getApiErrorMessage(error: unknown) {
  if (!isApiError(error)) {
    return genericApiErrorMessage;
  }

  return getApiErrorMessageByCode(error.code, error.requestId);
}

function withRequestId(message: string, requestId?: string) {
  return requestId ? `${message} شناسه درخواست: ${requestId}` : message;
}

export { apiErrorMessages, getApiErrorMessage, getApiErrorMessageByCode, withRequestId };
